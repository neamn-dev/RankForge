def seed_starter_templates(db: Session) -> int:
    """Seeds starter templates if they don't already exist by name."""
    existing_names = set(db.scalars(select(TemplateRow.name)))
    starters = get_starter_templates()
    added = 0
    for doc in starters:
        if doc.name not in existing_names:
            svc.create_template(db, doc)
            added += 1
    return added
